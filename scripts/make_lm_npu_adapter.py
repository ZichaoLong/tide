#!/usr/bin/env python3
"""Generate a site shim for an explicit, reviewed and expiring sharing policy.

Does not select cards or grant permission. The existing sharing adapter owns
identity/resource checks; the pinned site queue owns ordering and group locks.
"""
import argparse
import hashlib
from pathlib import Path
from run_shared_npu import validate_policy
from durable_records import replace_text
import json


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--policy',type=Path,required=True)
    p.add_argument('--helper',type=Path,required=True)
    p.add_argument('--output',type=Path,required=True)
    args=p.parse_args()
    policy=args.policy.resolve();helper=args.helper.resolve();output=args.output.resolve()
    validate_policy(json.loads(policy.read_text()))
    if output.exists():p.error('output exists; keep active adapters immutable')
    adapter=Path(__file__).resolve().with_name('run_shared_npu.py')
    helper_hash=hashlib.sha256(helper.read_bytes()).hexdigest()
    policy_hash=hashlib.sha256(policy.read_bytes()).hexdigest()
    source=f'''# Generated by make_lm_npu_adapter.py; immutable site configuration.
import hashlib
import os
from pathlib import Path
import sys
policy=Path({str(policy)!r})
if hashlib.sha256(policy.read_bytes()).hexdigest() != {policy_hash!r}:
    raise RuntimeError('active sharing policy changed')
state=Path(sys.argv[sys.argv.index('--state-file')+1])
os.execv(sys.executable,[sys.executable,'-B',{str(adapter)!r},'--helper',{str(helper)!r},
    '--helper-sha256',{helper_hash!r},'--policy',str(policy),
    '--audit',str(state.with_name('sharing-audit.jsonl')),'--',*sys.argv[1:]])
'''
    output.parent.mkdir(parents=True,exist_ok=True)
    replace_text(output,source)
    print(output)


if __name__=='__main__':main()
